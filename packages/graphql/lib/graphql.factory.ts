/**
 * Metadata that a field resolver decorated with field middleware can carry:
 * the resolver without any middleware, and the middleware of the handler
 * itself (global middleware excluded). It lets the middleware of a model field
 * run between the two, so that the global middleware still runs first.
 */
const FIELD_RESOLVER_COMPOSITION_METADATA =
  'graphql:field_resolver_composition';

interface FieldResolverComposition {
  resolve: (...args: unknown[]) => unknown;
  middleware: FieldMiddleware[];
}

type FieldResolver = GraphQLFieldResolver<unknown, unknown>;
type HasResolverFn = (typeName: string, fieldName: string) => boolean;

@Injectable()
export class GraphQLFactory {
  private readonly logger = new Logger(GraphQLFactory.name);

  constructor(
    private readonly resolversExplorerService: ResolversExplorerService,
    private readonly scalarsExplorerService: ScalarsExplorerService,
    private readonly graphqlAstExplorer: GraphQLAstExplorer,
    private readonly gqlSchemaBuilder: GraphQLSchemaBuilder,
  ) {}

  async generateSchema<T extends GqlModuleOptions>(
    options: T = { typeDefs: [] } as T,
  ): Promise<GraphQLSchema> {
    if (options.directiveResolvers) {
      this.logger.warn(
        'The "directiveResolvers" option is ignored (it has had no effect since v9.2.0): the directive resolvers passed through it are never called. Apply the directives with "transformSchema" instead (for example, with "mapSchema()" from "@graphql-tools/utils").',
      );
    }
    const resolvers = this.resolversExplorerService.explore();
    const rawResolvers = extend(
      this.scalarsExplorerService.explore(),
      resolvers,
    );

    const typesResolvers = options.transformResolvers
      ? await options.transformResolvers(rawResolvers)
      : rawResolvers;
    /**
     * Merge field by field, so that an entry of the "resolvers" option does
     * not replace the field resolvers discovered for the same type
     */
    const executableResolvers: IResolvers = mergeResolvers(
      [typesResolvers, options.resolvers].flat(),
    );

    const transformSchema = async (schema: GraphQLSchema) =>
      options.transformSchema ? await options.transformSchema(schema) : schema;

    if (options.autoSchemaFile) {
      const autoGeneratedSchema: GraphQLSchema =
        await this.gqlSchemaBuilder.build(
          options.autoSchemaFile,
          options,
          this.resolversExplorerService.getAllCtors(),
        );
      const executableSchema = makeExecutableSchema({
        resolvers: executableResolvers,
        typeDefs: gql`
          ${printSchema(autoGeneratedSchema)}
        `,
        resolverValidationOptions: {
          ...(options.resolverValidationOptions || {}),
          requireResolversForResolveType: 'ignore',
        },
        inheritResolversFromInterfaces: options.inheritResolversFromInterfaces,
      });
      let schema = options.schema
        ? mergeSchemas({
            schemas: [options.schema, executableSchema],
          })
        : executableSchema;

      const autoGeneratedSchemaConfig = autoGeneratedSchema.toConfig();
      const schemaConfig = this.overrideOrExtendResolvers(
        schema.toConfig(),
        autoGeneratedSchemaConfig,
        executableSchema,
        executableResolvers,
        options.buildSchemaOptions?.fieldMiddleware ?? [],
      );

      schema = new GraphQLSchema(schemaConfig);
      schema = await transformSchema(schema);
      schema = options.sortSchema ? lexicographicSortSchema(schema) : schema;
      return schema;
    }
    if (this.isEmptyValue(options.typeDefs)) {
      const schema = await transformSchema(options.schema);
      return schema;
    }
    const executableSchemaConfig = {
      resolvers: executableResolvers,
      typeDefs: gql`
        ${options.typeDefs}
      `,
      resolverValidationOptions: options.resolverValidationOptions,
      inheritResolversFromInterfaces: options.inheritResolversFromInterfaces,
    };
    /**
     * Merge the type definitions themselves (rather than a schema made
     * executable from them) into the "schema" option, so that a scalar or an
     * enum that both declare keeps the implementation of the "schema" option,
     * unless one is registered on the Nest side
     */
    let schema = options.schema
      ? mergeSchemas({
          schemas: [options.schema],
          ...executableSchemaConfig,
        })
      : makeExecutableSchema(executableSchemaConfig);

    if (options.inheritResolversFromInterfaces) {
      this.inheritResolversFromInterfaces(
        schema,
        options.schema
          ? mergeResolvers([
              getResolversFromSchema(options.schema),
              executableResolvers,
            ])
          : executableResolvers,
      );
    }
    removeTempField(schema);
    schema = await transformSchema(schema);
    schema = options.sortSchema ? lexicographicSortSchema(schema) : schema;
    return schema;
  }

  private overrideOrExtendResolvers(
    executableSchemaConfig: GraphQLSchemaConfig,
    autoGeneratedSchemaConfig: GraphQLSchemaConfig,
    executableSchema: GraphQLSchema,
    resolvers: IResolvers,
    globalMiddleware: FieldMiddleware[],
  ): GraphQLSchemaConfig {
    const schemaConfig = autoGeneratedSchemaConfig;
    const rootResolverKeys: ('mutation' | 'query' | 'subscription')[] = [
      'mutation',
      'query',
      'subscription',
    ];

    rootResolverKeys
      .filter((key) => executableSchemaConfig[key] && schemaConfig[key])
      .forEach((key) => {
        const executableSchemaFields = executableSchemaConfig[key].getFields();
        const schemaFields = schemaConfig[key].getFields();

        Object.entries(executableSchemaFields).forEach(
          ([resolverName, value]) => {
            if (schemaFields[resolverName]) {
              schemaFields[resolverName].resolve =
                executableSchemaFields[resolverName].resolve;
              schemaFields[resolverName].subscribe =
                executableSchemaFields[resolverName].subscribe;
            } else {
              schemaFields[resolverName] = value;
            }
          },
        );
      });

    const rootTypes = new Set<GraphQLNamedType>(
      rootResolverKeys.map((key) => schemaConfig[key]).filter(Boolean),
    );
    const typesByName = new Map(
      schemaConfig.types.map((type) => [type.name, type]),
    );
    const mergedTypesByName = new Map(
      executableSchemaConfig.types.map((type) => [type.name, type]),
    );
    const metadataByName = this.getTypeMetadataByName();
    const resolverOnlyFields = this.getResolverOnlyFields();
    const isResolverOnlyField = (field: PropertyMetadata) =>
      resolverOnlyFields.typeFns.has(field.typeFn);

    /**
     * The supertypes of a type are the interfaces it implements and the
     * (object or interface) type its class extends
     */
    const getSupertypes = (typeName: string): string[] => {
      const type = typesByName.get(typeName);
      if (!isObjectType(type) && !isInterfaceType(type)) {
        return [];
      }
      const supertypes = type.getInterfaces().map(({ name }) => name);
      const parentMetadata = this.getParentTypeMetadata(
        metadataByName.get(typeName),
        ({ name }) => typesByName.has(name),
      );
      if (parentMetadata) {
        supertypes.push(parentMetadata.name);
      }
      return supertypes;
    };
    const findResolverHost = this.createResolverHostLookup(
      getSupertypes,
      (typeName, fieldName) =>
        this.hasOwnResolver(resolvers, typeName, fieldName) &&
        !!this.getFieldResolve(executableSchema, typeName, fieldName),
    );
    const unboundFields: string[] = [];

    schemaConfig.types
      .filter(isObjectType)
      .filter((type) => !rootTypes.has(type))
      .forEach((type) => {
        const metadata = metadataByName.get(type.name);
        const mergedType = mergedTypesByName.get(type.name);

        Object.entries(type.getFields()).forEach(([fieldName, field]) => {
          /**
           * Bind the resolver of the type itself or, if it has none, the one
           * of its most specific supertype (interfaces and parent classes)
           */
          const hostName = findResolverHost(type.name, fieldName);
          if (hostName) {
            field.resolve = this.withModelFieldMiddleware(
              this.getFieldResolve(executableSchema, hostName, fieldName),
              this.getRawResolver(resolvers, hostName, fieldName),
              metadata
                ? this.getModelFieldMiddleware(
                    metadata,
                    fieldName,
                    isResolverOnlyField,
                  )
                : [],
              globalMiddleware,
            );
            return;
          }
          /**
           * Keep the resolvers of the "schema" option for a type of the same name
           */
          const mergedResolve =
            isObjectType(mergedType) &&
            mergedType !== executableSchema.getType(type.name)
              ? mergedType.getFields()[fieldName]?.resolve
              : undefined;
          if (mergedResolve) {
            field.resolve = mergedResolve;
            return;
          }
          /**
           * Fail closed: a field that only a field resolver declares (the model
           * has no such field) must not fall back to the parent's property
           */
          const fieldMetadata =
            metadata &&
            resolverOnlyFields.names.has(fieldName) &&
            this.findFieldMetadata(metadata, fieldName);
          if (fieldMetadata && isResolverOnlyField(fieldMetadata)) {
            field.resolve = this.createUnboundFieldResolver(
              type.name,
              fieldName,
            );
            unboundFields.push(`"${type.name}.${fieldName}"`);
          }
        });
      });

    if (unboundFields.length > 0) {
      this.logger.warn(
        `No resolver is bound for these fields, which are declared only by a field resolver (@ResolveField()): ${unboundFields.join(
          ', ',
        )}. Selecting them throws an error.`,
      );
    }
    return schemaConfig;
  }

  /**
   * "@graphql-tools/schema" lets the interface that a type lists last win, so
   * a base interface listed after an interface that implements it replaces the
   * resolver of the more specific interface (and the guards wrapped around it).
   * Binds the resolver of the most specific interface instead.
   */
  private inheritResolversFromInterfaces(
    schema: GraphQLSchema,
    resolvers: IResolvers,
  ) {
    const hasResolver: HasResolverFn = (typeName, fieldName) =>
      this.hasOwnResolver(resolvers, typeName, fieldName) &&
      !!this.getFieldResolve(schema, typeName, fieldName);
    const findResolverHost = this.createResolverHostLookup((typeName) => {
      const type = schema.getType(typeName);
      return isObjectType(type) || isInterfaceType(type)
        ? type.getInterfaces().map(({ name }) => name)
        : [];
    }, hasResolver);

    Object.values(schema.getTypeMap())
      .filter(isObjectType)
      .forEach((type) => {
        const interfaces = type.getInterfaces();
        Object.entries(type.getFields()).forEach(([fieldName, field]) => {
          const hostName = findResolverHost(type.name, fieldName);
          const listedLast = [...interfaces]
            .reverse()
            .find((interfaceRef) => hasResolver(interfaceRef.name, fieldName));
          if (hostName !== type.name && hostName !== listedLast?.name) {
            field.resolve = this.getFieldResolve(schema, hostName, fieldName);
          }
        });
      });
  }

  /**
   * Returns a function that finds the type whose resolver of a field is bound
   * to a type: the type itself if it has one or else, among its supertypes
   * that have one, the most specific. Among unrelated supertypes, the parent
   * class wins over interfaces, and the interface listed last wins over the others.
   */
  private createResolverHostLookup(
    getSupertypes: (typeName: string) => string[],
    hasResolver: HasResolverFn,
  ) {
    const ancestorsByType = new Map<string, string[]>();
    const getAncestors = (typeName: string): string[] => {
      if (!ancestorsByType.has(typeName)) {
        const ancestors: string[] = [];
        const queue = [typeName];
        while (queue.length > 0) {
          for (const supertype of getSupertypes(queue.shift())) {
            if (supertype !== typeName && !ancestors.includes(supertype)) {
              ancestors.push(supertype);
              queue.push(supertype);
            }
          }
        }
        ancestorsByType.set(typeName, ancestors);
      }
      return ancestorsByType.get(typeName);
    };

    return (typeName: string, fieldName: string): string | undefined => {
      if (hasResolver(typeName, fieldName)) {
        return typeName;
      }
      const candidates = getAncestors(typeName).filter((ancestor) =>
        hasResolver(ancestor, fieldName),
      );
      const mostSpecific = candidates.filter(
        (candidate) =>
          !candidates.some((other) => getAncestors(other).includes(candidate)),
      );
      return mostSpecific[mostSpecific.length - 1];
    };
  }

  private hasOwnResolver(
    resolvers: IResolvers,
    typeName: string,
    fieldName: string,
  ): boolean {
    const typeResolvers = resolvers[typeName];
    return (
      typeof typeResolvers === 'object' &&
      typeResolvers !== null &&
      Object.prototype.hasOwnProperty.call(typeResolvers, fieldName) &&
      typeResolvers[fieldName] != null
    );
  }

  private getRawResolver(
    resolvers: IResolvers,
    typeName: string,
    fieldName: string,
  ): unknown {
    const resolver = (resolvers[typeName] as Record<string, any>)?.[fieldName];
    return typeof resolver === 'function' ? resolver : resolver?.resolve;
  }

  private getFieldResolve(
    schema: GraphQLSchema,
    typeName: string,
    fieldName: string,
  ): FieldResolver | undefined {
    const type = schema.getType(typeName);
    return isObjectType(type) || isInterfaceType(type)
      ? type.getFields()[fieldName]?.resolve
      : undefined;
  }

  /**
   * Wraps the resolver bound to a field with the middleware that the model
   * declares for that field (which the resolver generated for the field runs
   * too), instead of dropping that middleware.
   */
  private withModelFieldMiddleware(
    resolve: FieldResolver,
    rawResolver: unknown,
    modelMiddleware: FieldMiddleware[],
    globalMiddleware: FieldMiddleware[],
  ): FieldResolver {
    if (modelMiddleware.length === 0) {
      return resolve;
    }
    const composition: FieldResolverComposition | undefined =
      typeof rawResolver === 'function'
        ? Reflect.getMetadata(FIELD_RESOLVER_COMPOSITION_METADATA, rawResolver)
        : undefined;
    if (!composition) {
      return decorateFieldResolverWithMiddleware(
        (...args) =>
          () =>
            resolve(...args),
        modelMiddleware,
      );
    }
    // The global middleware first, then the model's and the handler's, each once
    return decorateFieldResolverWithMiddleware(
      (...args) =>
        () =>
          composition.resolve(...args),
      [
        ...globalMiddleware,
        ...modelMiddleware.filter(
          (middleware) => !composition.middleware.includes(middleware),
        ),
        ...composition.middleware,
      ],
    );
  }

  private createUnboundFieldResolver(
    typeName: string,
    fieldName: string,
  ): FieldResolver {
    return () => {
      throw new GraphQLError(
        `No resolver is bound for field "${typeName}.${fieldName}".`,
      );
    };
  }

  private getTypeMetadataByName(): Map<string, ObjectTypeMetadata> {
    const metadataByName = new Map<string, ObjectTypeMetadata>();
    const metadata = [
      ...TypeMetadataStorage.getObjectTypesMetadata(),
      ...TypeMetadataStorage.getInterfacesMetadata(),
    ];
    for (const item of metadata) {
      if (!item.isAbstract && !metadataByName.has(item.name)) {
        metadataByName.set(item.name, item);
      }
    }
    return metadataByName;
  }

  /**
   * Returns the "typeFn" (and the names) of the fields that the field
   * resolvers add to a type when the model declares no field of that name.
   */
  private getResolverOnlyFields() {
    // Not exposed by "TypeMetadataStorage"
    const fieldResolvers: FieldResolverMetadata[] = (
      TypeMetadataStorage['fieldResolvers'] ?? []
    ).filter(
      (item: FieldResolverMetadata) => item.kind === 'external' && item.typeFn,
    );
    return {
      typeFns: new Set<Function>(fieldResolvers.map((item) => item.typeFn)),
      names: new Set(fieldResolvers.map((item) => item.schemaName)),
    };
  }

  /**
   * Returns the metadata of the nearest class up the prototype chain that is
   * an object or an interface type (and matches the predicate).
   */
  private getParentTypeMetadata(
    metadata: ObjectTypeMetadata | undefined,
    predicate: (metadata: ObjectTypeMetadata) => boolean = () => true,
  ): ObjectTypeMetadata | undefined {
    let parent = metadata && Object.getPrototypeOf(metadata.target);
    while (parent && parent !== Function.prototype) {
      const parentMetadata =
        TypeMetadataStorage.getObjectTypeMetadataByTarget(parent) ??
        TypeMetadataStorage.getInterfaceMetadataByTarget(parent);
      if (parentMetadata && predicate(parentMetadata)) {
        return parentMetadata;
      }
      parent = Object.getPrototypeOf(parent);
    }
    return undefined;
  }

  private getInterfacesMetadata(
    metadata: ObjectTypeMetadata,
  ): ObjectTypeMetadata[] {
    const interfaces: ObjectTypeMetadata[] = [];
    const queue = [metadata];
    while (queue.length > 0) {
      for (const target of getInterfacesArray(queue.shift().interfaces)) {
        const item = TypeMetadataStorage.getInterfaceMetadataByTarget(target);
        if (item && !interfaces.includes(item)) {
          interfaces.push(item);
          queue.push(item);
        }
      }
    }
    return interfaces;
  }

  /**
   * Returns the nearest declaration of a field that matches the predicate:
   * the type's own, or else an interface's, or else the parent class's.
   */
  private findFieldMetadata(
    metadata: ObjectTypeMetadata,
    fieldName: string,
    predicate: (field: PropertyMetadata) => boolean = () => true,
  ): PropertyMetadata | undefined {
    const visited = new Set<ObjectTypeMetadata>();
    for (
      let current = metadata;
      current && !visited.has(current);
      current = this.getParentTypeMetadata(current)
    ) {
      visited.add(current);
      for (const item of [current, ...this.getInterfacesMetadata(current)]) {
        const field = [...(item.properties ?? [])]
          .reverse()
          .find(
            (property) =>
              property.schemaName === fieldName && predicate(property),
          );
        if (field) {
          return field;
        }
      }
    }
    return undefined;
  }

  /**
   * Returns the middleware that the model declares for a field with
   * "@Field({ middleware })" and "@UseFieldMiddleware()" (no global middleware).
   */
  private getModelFieldMiddleware(
    metadata: ObjectTypeMetadata,
    fieldName: string,
    isResolverOnlyField: (field: PropertyMetadata) => boolean,
  ): FieldMiddleware[] {
    const field = this.findFieldMetadata(
      metadata,
      fieldName,
      (property) => !isResolverOnlyField(property),
    );
    return field
      ? (field.middleware ?? []).concat(
          getUseFieldMiddleware(field.target?.prototype, field.name),
        )
      : [];
  }

  async generateDefinitions(
    typeDefs: string | string[],
    options: GqlModuleOptions,
  ) {
    if (this.isEmptyValue(typeDefs) || !options.definitions) {
      return;
    }
    const definitionsGeneratorOptions: DefinitionsGeneratorOptions = {
      emitTypenameField: options.definitions.emitTypenameField,
      skipResolverArgs: options.definitions.skipResolverArgs,
      defaultScalarType: options.definitions.defaultScalarType,
      customScalarTypeMapping: options.definitions.customScalarTypeMapping,
      additionalHeader: options.definitions.additionalHeader,
      defaultTypeMapping: options.definitions.defaultTypeMapping,
      enumsAsTypes: options.definitions.enumsAsTypes,
      typeName: options.definitions.typeName,
    };
    const tsFile = await this.graphqlAstExplorer.explore(
      gql`
        ${typeDefs}
      `,
      options.definitions.path,
      options.definitions.outputAs,
      definitionsGeneratorOptions,
    );
    if (
      !existsSync(options.definitions.path) ||
      !lstatSync(options.definitions.path).isFile() ||
      readFileSync(options.definitions.path, 'utf8') !== tsFile.getFullText()
    ) {
      await tsFile.save();
    }
  }

  private isEmptyValue(value: unknown) {
    if (value == null) {
      return true;
    }
    if (Array.isArray(value) || typeof value === 'string') {
      return value.length === 0;
    }
    return false;
  }
}
